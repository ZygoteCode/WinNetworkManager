using System.Collections.Concurrent;
using System.Globalization;
using System.Runtime.InteropServices;
using System.Text;
using Microsoft.Win32.SafeHandles;
using static WinNetworkManager.Platform.Windows.Interop.WinTrustNative;

namespace WinNetworkManager.Platform.Windows.Processes;

/// <summary>Outcome of an Authenticode check.</summary>
public enum SignatureStatus : byte
{
    /// <summary>Not checked yet.</summary>
    Unknown = 0,

    /// <summary>Signed and the chain is trusted (revocation not checked online).</summary>
    Valid,

    /// <summary>No embedded signature and no catalog entry.</summary>
    Unsigned,

    /// <summary>Signed but the chain ends in an untrusted root.</summary>
    UntrustedRoot,

    /// <summary>The file content does not match its signature.</summary>
    BadDigest,

    /// <summary>The signing certificate (or chain) is explicitly distrusted or revoked.</summary>
    Distrusted,

    /// <summary>Signature present but invalid for another reason (expired without timestamp, policy…).</summary>
    Invalid,

    /// <summary>The file could not be read.</summary>
    FileError,
}

/// <summary>Signature details.</summary>
/// <param name="Status">Verification status.</param>
/// <param name="SignerName">Simple display name of the signing certificate subject (the publisher).</param>
/// <param name="IssuerName">Issuer of the signing certificate.</param>
/// <param name="IsCatalogSigned">True when the signature comes from a system catalog rather than the file itself.</param>
/// <param name="ErrorCode">WinVerifyTrust HRESULT.</param>
public sealed record SignatureInfo(SignatureStatus Status, string? SignerName, string? IssuerName, bool IsCatalogSigned, int ErrorCode)
{
    /// <summary>User-facing status text.</summary>
    public string Describe() => Status switch
    {
        SignatureStatus.Valid => IsCatalogSigned ? "Valid (catalog)" : "Valid",
        SignatureStatus.Unsigned => "Not signed",
        SignatureStatus.UntrustedRoot => "Untrusted root",
        SignatureStatus.BadDigest => "Tampered (hash mismatch)",
        SignatureStatus.Distrusted => "Distrusted / revoked",
        SignatureStatus.Invalid => string.Create(CultureInfo.InvariantCulture, $"Invalid (0x{ErrorCode:X8})"),
        SignatureStatus.FileError => "File not readable",
        _ => "Unknown",
    };
}

/// <summary>
/// Verifies Authenticode signatures of executables, including catalog-signed Windows binaries. Revocation is not
/// checked online (no network traffic is generated by the monitor itself); results are cached per file version.
/// Calls can take tens of milliseconds: never call on the UI thread.
/// </summary>
public static unsafe class AuthenticodeVerifier
{
    private static readonly ConcurrentDictionary<(string Path, long Size, long Write), SignatureInfo> Cache = new(StringTupleComparer.Instance);

    /// <summary>Verifies <paramref name="path"/>.</summary>
    public static SignatureInfo Verify(string path)
    {
        ArgumentException.ThrowIfNullOrEmpty(path);
        FileInfo file;
        try
        {
            file = new FileInfo(path);
            if (!file.Exists)
            {
                return new SignatureInfo(SignatureStatus.FileError, null, null, false, CRYPT_E_FILE_ERROR);
            }
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
        {
            return new SignatureInfo(SignatureStatus.FileError, null, null, false, CRYPT_E_FILE_ERROR);
        }

        var key = (file.FullName, file.Length, file.LastWriteTimeUtc.Ticks);
        if (Cache.TryGetValue(key, out var cached))
        {
            return cached;
        }

        var result = VerifyEmbedded(file.FullName);
        if (result.Status == SignatureStatus.Unsigned)
        {
            var catalog = VerifyCatalog(file.FullName);
            if (catalog is not null)
            {
                result = catalog;
            }
        }

        if (Cache.Count > 4096)
        {
            Cache.Clear();
        }

        Cache[key] = result;
        return result;
    }

    private static SignatureInfo VerifyEmbedded(string path)
    {
        fixed (char* pPath = path)
        {
            var fileInfo = new WINTRUST_FILE_INFO { cbStruct = (uint)sizeof(WINTRUST_FILE_INFO), pcwszFilePath = pPath };
            var data = new WINTRUST_DATA
            {
                cbStruct = (uint)sizeof(WINTRUST_DATA),
                dwUIChoice = WTD_UI_NONE,
                fdwRevocationChecks = WTD_REVOKE_NONE,
                dwUnionChoice = WTD_CHOICE_FILE,
                pInfo = &fileInfo,
                dwStateAction = WTD_STATEACTION_VERIFY,
                dwProvFlags = WTD_REVOCATION_CHECK_NONE | WTD_CACHE_ONLY_URL_RETRIEVAL | WTD_DISABLE_MD2_MD4,
            };
            return RunVerification(&data, isCatalog: false);
        }
    }

    private static SignatureInfo? VerifyCatalog(string path)
    {
        SafeFileHandle handle;
        try
        {
            handle = File.OpenHandle(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
        {
            return new SignatureInfo(SignatureStatus.FileError, null, null, false, CRYPT_E_FILE_ERROR);
        }

        using (handle)
        {
            if (!CryptCATAdminAcquireContext2(out nint admin, null, "SHA256", 0, 0))
            {
                return null;
            }

            try
            {
                uint hashSize = 0;
                CryptCATAdminCalcHashFromFileHandle2(admin, handle, &hashSize, null, 0);
                if (hashSize is 0 or > 256)
                {
                    return null;
                }

                byte* hash = stackalloc byte[(int)hashSize];
                if (!CryptCATAdminCalcHashFromFileHandle2(admin, handle, &hashSize, hash, 0))
                {
                    return null;
                }

                nint catInfo = CryptCATAdminEnumCatalogFromHash(admin, hash, hashSize, 0, null);
                if (catInfo == 0)
                {
                    return null; // genuinely unsigned
                }

                try
                {
                    var info = new CATALOG_INFO { cbStruct = (uint)sizeof(CATALOG_INFO) };
                    if (!CryptCATCatalogInfoFromContext(catInfo, &info, 0))
                    {
                        return null;
                    }

                    string catalogPath = new(info.wszCatalogFile);
                    string memberTag = ToHex(new ReadOnlySpan<byte>(hash, (int)hashSize));
                    fixed (char* pCatalog = catalogPath)
                    fixed (char* pTag = memberTag)
                    fixed (char* pPath = path)
                    {
                        var catalog = new WINTRUST_CATALOG_INFO
                        {
                            cbStruct = (uint)sizeof(WINTRUST_CATALOG_INFO),
                            pcwszCatalogFilePath = pCatalog,
                            pcwszMemberTag = pTag,
                            pcwszMemberFilePath = pPath,
                            hMemberFile = handle.DangerousGetHandle(),
                            pbCalculatedFileHash = hash,
                            cbCalculatedFileHash = hashSize,
                            hCatAdmin = admin,
                        };
                        var data = new WINTRUST_DATA
                        {
                            cbStruct = (uint)sizeof(WINTRUST_DATA),
                            dwUIChoice = WTD_UI_NONE,
                            fdwRevocationChecks = WTD_REVOKE_NONE,
                            dwUnionChoice = WTD_CHOICE_CATALOG,
                            pInfo = &catalog,
                            dwStateAction = WTD_STATEACTION_VERIFY,
                            dwProvFlags = WTD_REVOCATION_CHECK_NONE | WTD_CACHE_ONLY_URL_RETRIEVAL,
                        };
                        return RunVerification(&data, isCatalog: true);
                    }
                }
                finally
                {
                    CryptCATAdminReleaseCatalogContext(admin, catInfo, 0);
                }
            }
            finally
            {
                CryptCATAdminReleaseContext(admin, 0);
            }
        }
    }

    private static SignatureInfo RunVerification(WINTRUST_DATA* data, bool isCatalog)
    {
        Guid action = WINTRUST_ACTION_GENERIC_VERIFY_V2;
        int hr = WinVerifyTrust(-1, &action, data); // INVALID_HANDLE_VALUE: no UI
        string? signer = null;
        string? issuer = null;
        try
        {
            if (data->hWVTStateData != 0 && hr is 0 or CERT_E_UNTRUSTEDROOT or CERT_E_CHAINING or CERT_E_EXPIRED or TRUST_E_EXPLICIT_DISTRUST or CERT_E_REVOKED)
            {
                (signer, issuer) = ReadSigner(data->hWVTStateData);
            }
        }
        finally
        {
            data->dwStateAction = WTD_STATEACTION_CLOSE;
            WinVerifyTrust(-1, &action, data);
        }

        var status = hr switch
        {
            0 => SignatureStatus.Valid,
            TRUST_E_NOSIGNATURE or TRUST_E_SUBJECT_FORM_UNKNOWN or TRUST_E_PROVIDER_UNKNOWN => SignatureStatus.Unsigned,
            CERT_E_UNTRUSTEDROOT or CERT_E_CHAINING => SignatureStatus.UntrustedRoot,
            TRUST_E_BAD_DIGEST => SignatureStatus.BadDigest,
            TRUST_E_EXPLICIT_DISTRUST or CERT_E_REVOKED => SignatureStatus.Distrusted,
            CRYPT_E_FILE_ERROR => SignatureStatus.FileError,
            _ => SignatureStatus.Invalid,
        };

        return new SignatureInfo(status, signer, issuer, isCatalog && status != SignatureStatus.Unsigned, hr);
    }

    private static (string? Signer, string? Issuer) ReadSigner(nint stateData)
    {
        nint provData = WTHelperProvDataFromStateData(stateData);
        if (provData == 0)
        {
            return (null, null);
        }

        nint signerPtr = WTHelperGetProvSignerFromChain(provData, 0, false, 0);
        if (signerPtr == 0)
        {
            return (null, null);
        }

        // CRYPT_PROVIDER_SGNR: cbStruct(4) sftVerifyAsOf(8) csCertChain(4) pasCertChain(ptr) …
        uint chainLength = *(uint*)((byte*)signerPtr + 12);
        nint chain = *(nint*)((byte*)signerPtr + 16);
        if (chainLength == 0 || chain == 0)
        {
            return (null, null);
        }

        // CRYPT_PROVIDER_CERT: cbStruct(4) pCert(ptr) …
        nint certContext = *(nint*)((byte*)chain + IntPtr.Size);
        if (certContext == 0)
        {
            return (null, null);
        }

        return (GetName(certContext, 0), GetName(certContext, CERT_NAME_ISSUER_FLAG));
    }

    private static string? GetName(nint certContext, uint flags)
    {
        char* buffer = stackalloc char[512];
        uint length = CertGetNameString(certContext, CERT_NAME_SIMPLE_DISPLAY_TYPE, flags, null, buffer, 512);
        return length > 1 ? new string(buffer, 0, (int)length - 1) : null;
    }

    private static string ToHex(ReadOnlySpan<byte> bytes)
    {
        var sb = new StringBuilder(bytes.Length * 2);
        foreach (byte b in bytes)
        {
            sb.Append(b.ToString("X2", CultureInfo.InvariantCulture));
        }

        return sb.ToString();
    }

    private sealed class StringTupleComparer : IEqualityComparer<(string Path, long Size, long Write)>
    {
        public static readonly StringTupleComparer Instance = new();

        public bool Equals((string Path, long Size, long Write) x, (string Path, long Size, long Write) y) =>
            x.Size == y.Size && x.Write == y.Write && string.Equals(x.Path, y.Path, StringComparison.OrdinalIgnoreCase);

        public int GetHashCode((string Path, long Size, long Write) obj) =>
            HashCode.Combine(StringComparer.OrdinalIgnoreCase.GetHashCode(obj.Path), obj.Size, obj.Write);
    }

    internal static (int Data, int File, int Catalog) StructSizes =>
        (sizeof(WINTRUST_DATA), sizeof(WINTRUST_FILE_INFO), sizeof(WINTRUST_CATALOG_INFO));

    internal static bool IsSafeHandleValid(SafeHandle handle) => !handle.IsInvalid;
}
